# Pre-build hook: gzip every file in data/ into lib/WebApi/WebAssets.h so the
# web UI ships inside firmware.bin (one OTA update, UI and API never drift).
# Standalone: python3 tools/embed_web.py
import gzip
import hashlib
import os

MIME = {
    ".html": "text/html; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".js": "application/javascript; charset=utf-8",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".ico": "image/x-icon",
    ".json": "application/json",
}


def embed(project_dir):
    data_dir = os.path.join(project_dir, "data")
    out_path = os.path.join(project_dir, "lib", "WebApi", "WebAssets.h")

    files = []
    for root, _, names in os.walk(data_dir):
        for name in sorted(names):
            full = os.path.join(root, name)
            rel = "/" + os.path.relpath(full, data_dir).replace(os.sep, "/")
            ext = os.path.splitext(name)[1].lower()
            if ext not in MIME:
                continue
            with open(full, "rb") as f:
                raw = f.read()
            files.append((rel, MIME[ext], gzip.compress(raw, compresslevel=9, mtime=0), len(raw)))
    files.sort()

    etag = hashlib.sha1(b"".join(path.encode() + body for path, _, body, _ in files)).hexdigest()[:16]
    lines = [
        "// Generated by tools/embed_web.py from data/ - do not edit.",
        "#ifndef WEB_ASSETS_H",
        "#define WEB_ASSETS_H",
        "",
        "#include <Arduino.h>",
        "",
        "struct WebAsset {",
        "    const char* path;",
        "    const char* mime;",
        "    const uint8_t* gzip;",
        "    size_t length;",
        "};",
        "",
    ]
    for i, (path, _, body, raw_len) in enumerate(files):
        lines.append(f"// {path}: {raw_len} bytes, {len(body)} gzipped")
        lines.append(f"static const uint8_t WEB_ASSET_{i}[] PROGMEM = {{")
        for off in range(0, len(body), 24):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in body[off:off + 24]) + ",")
        lines.append("};")
    lines.append("")
    lines.append("static const WebAsset WEB_ASSETS[] = {")
    for i, (path, mime, body, _) in enumerate(files):
        lines.append(f'    {{"{path}", "{mime}", WEB_ASSET_{i}, {len(body)}}},')
    lines.append("};")
    lines.append(f"static const size_t WEB_ASSET_COUNT = {len(files)};")
    lines.append(f'static const char WEB_ASSETS_ETAG[] = "\\"{etag}\\"";')
    lines.append("")
    lines.append("#endif")
    content = "\n".join(lines) + "\n"

    previous = open(out_path).read() if os.path.exists(out_path) else None
    if content != previous:   # keep the timestamp when nothing changed: no needless rebuilds
        with open(out_path, "w") as f:
            f.write(content)
    total = sum(len(body) for _, _, body, _ in files)
    print(f"Embedded web UI: {len(files)} files, {total} bytes gzipped, ETag {etag}")


try:
    Import("env")  # noqa: F821 - provided by PlatformIO/SCons
    embed(env["PROJECT_DIR"])  # noqa: F821
except NameError:
    embed(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
