"""PlatformIO pre-build step: writes lib/Core/BuildVersion.h (git-ignored) with
FW_VERSION, so every image reports what it was built from:

- the FW_VERSION environment variable if set (the release workflow passes the
  release tag, e.g. v2026.10.23.1830),
- otherwise `git describe --tags --always --dirty` (e.g. v2026.10.23.1830-3-g1a2b3c4,
  or 1a2b3c4-dirty for uncommitted changes),
- otherwise "dev" (no git, e.g. a source archive).

The header is only rewritten when the version changes, so it doesn't force a
full rebuild.
"""
import os
import subprocess
from pathlib import Path


def firmware_version(project_dir):
    if os.environ.get("FW_VERSION"):
        return os.environ["FW_VERSION"]
    try:
        out = subprocess.run(["git", "describe", "--tags", "--always", "--dirty"], cwd=project_dir,
                             capture_output=True, text=True, check=True, timeout=10).stdout.strip()
        return out or "dev"
    except (OSError, subprocess.SubprocessError):
        return "dev"


def write_header(project_dir):
    version = firmware_version(project_dir).replace('"', "")
    header = Path(project_dir) / "lib/Core/BuildVersion.h"
    text = f'// Generated by tools/version.py - do not edit.\n#define FW_VERSION "{version}"\n'
    if not header.exists() or header.read_text() != text:
        header.write_text(text)
    print(f"Firmware version: {version}")


try:
    Import("env")  # noqa: F821 - provided by PlatformIO
    write_header(env["PROJECT_DIR"])  # noqa: F821
except NameError:
    write_header(Path(__file__).resolve().parents[1])
